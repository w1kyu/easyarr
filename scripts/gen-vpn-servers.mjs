#!/usr/bin/env node
// Generates dashboard/shared/src/vpn-servers.generated.ts from Gluetun's server list
// (internal/storage/servers.json) at the Gluetun version EasyArr ships.
//
//   node scripts/gen-vpn-servers.mjs            # download from GitHub (version below)
//   node scripts/gen-vpn-servers.mjs --check    # fail if the committed file is out of date
//
// The file lists, per provider and protocol, the locations the user can pick in the wizard and which
// of them support port forwarding. Bump GLUETUN_VERSION together with the vpn/Dockerfile base image.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GLUETUN_VERSION = 'v3.41.3';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'dashboard/shared/src/vpn-servers.generated.ts');

const url = `https://raw.githubusercontent.com/qdm12/gluetun/${GLUETUN_VERSION}/internal/storage/servers.json`;
const res = await fetch(url);
if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
const data = await res.json();

/** Which server field the location filter uses: the first one every server has. */
const FIELDS = [
  ['country', 'SERVER_COUNTRIES'],
  ['region', 'SERVER_REGIONS'],
  ['city', 'SERVER_CITIES'],
];

const sortUnique = (values) =>
  [...new Set(values.filter(Boolean))].sort((a, b) => a.localeCompare(b, 'en'));

const providers = {};
for (const [name, value] of Object.entries(data)) {
  if (name === 'version' || typeof value !== 'object' || !Array.isArray(value.servers)) continue;
  const servers = value.servers;
  const field = FIELDS.find(([key]) => servers.every((s) => s[key]));
  const byProtocol = {};
  for (const protocol of ['wireguard', 'openvpn']) {
    const list = servers.filter((s) => s.vpn === protocol);
    if (list.length === 0) continue;
    byProtocol[protocol] = {
      servers: list.length,
      locations: field ? sortUnique(list.map((s) => s[field[0]])) : [],
      portForwardLocations: field
        ? sortUnique(list.filter((s) => s.port_forward).map((s) => s[field[0]]))
        : [],
      freeLocations: field ? sortUnique(list.filter((s) => s.free).map((s) => s[field[0]])) : [],
    };
  }
  providers[name] = { locationEnv: field ? field[1] : null, protocols: byProtocol };
}

const body = `// Generated by scripts/gen-vpn-servers.mjs from Gluetun ${GLUETUN_VERSION} — do not edit.
// Source: ${url}


export const GLUETUN_VERSION = '${GLUETUN_VERSION}';

export interface GluetunProtocolServers {
  servers: number;
  locations: readonly string[];
  portForwardLocations: readonly string[];
  freeLocations: readonly string[];
}

export interface GluetunProviderServers {
  /** Gluetun env var for the location filter, or null when servers have no location data. */
  locationEnv: 'SERVER_COUNTRIES' | 'SERVER_REGIONS' | 'SERVER_CITIES' | null;
  protocols: Partial<Record<'wireguard' | 'openvpn', GluetunProtocolServers>>;
}

export const GLUETUN_SERVERS: Record<string, GluetunProviderServers> = ${JSON.stringify(providers)};
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8');
  // Formatting is Prettier's business; compare the data only.
  const norm = (s) => s.replace(/\s+/g, '');
  if (norm(current) !== norm(body)) {
    console.error(
      `${path.relative(root, out)} is out of date: run node scripts/gen-vpn-servers.mjs`,
    );
    process.exit(1);
  }
  console.log('vpn-servers.generated.ts is up to date');
} else {
  writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)} (${Object.keys(providers).length} providers)`);
}
